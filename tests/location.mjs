import assert from 'node:assert/strict';
import {validPosition, freshPosition, fixedLocation, usableOrigin, drivingURL} from '../aetherlink_scout/static/location.mjs';
assert.equal(validPosition(NaN,10),false);
assert.equal(validPosition(91,10),false);
assert.equal(validPosition(0,0),true);
const origin={lat:35,lon:-115,updated:100000};
assert.equal(freshPosition(origin,100100),true);
assert.equal(freshPosition(origin,160000),false);
assert.equal(freshPosition(origin,99999),false);
const url=new URL(drivingURL({lat:36,lon:-116},origin,100100));
assert.equal(url.hostname,'www.google.com');
assert.equal(url.searchParams.get('origin'),'35,-115');
assert.equal(url.searchParams.get('destination'),'36,-116');
assert.equal(url.searchParams.get('travelmode'),'driving');
assert.equal(url.searchParams.get('api'),'1');
assert.equal(new URL(drivingURL({lat:36,lon:-116},origin,160000)).searchParams.has('origin'),false);
assert.equal(drivingURL({lat:NaN,lon:0}),null);
const fixed=fixedLocation({lat:35.009,lon:-115.013});
assert.equal(fixed.accuracy,null);
assert.equal(freshPosition(fixed,100000),false);
assert.equal(usableOrigin(fixed,100000000),true);
assert.equal(new URL(drivingURL({lat:36,lon:-116},fixed,100000000)).searchParams.get('origin'),'35.009,-115.013');
assert.equal(fixedLocation({lat:'35',lon:-115}),null);
assert.equal(fixedLocation({lat:91,lon:0}),null);
assert.equal(fixedLocation(null),null);
console.log('PASS: coordinate validation, browser-fix age, fixed manual origin, driving URL, stale browser origin omission');
